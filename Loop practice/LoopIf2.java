public class LoopIf2
{
    public static void main(String[] args)
  {
        for(int e = 0; e <= 15; e++) {
          if(e % 2 == 0) {
            System.out.println("Even");
          }  
            else {
               System.out.println(e);     
            }
        
        }

  }  

}